import { DEFAULT_PROVIDERS, type ProviderId, type ProviderModelConfig } from "./providers.ts";

/**
 * Дефолты AI-части. Хранятся в PartSetting(partId="ai", key="config") и
 * редактируются из панели без передеплоя. Файл только даёт начальное
 * значение при первом запуске.
 *
 * Идея: бот появляется в разговоре не как случайный ГПТ-фонтан, а с
 * ощущением, что он следит за беседой — иногда шутит вообще про тему,
 * иногда подкалывает конкретного участника, иногда язвит, иногда хвалит.
 * При этом стоимость не должна расти вместе с активностью чата — см.
 * dialog.ts (бюджет по символам + роллинг-саммари вместо "последние N
 * сообщений") и cooldown.ts/index.ts (частота вызовов развязана с
 * активностью), а провайдер и месячный $ бюджет — см. providers.ts/budget.ts.
 */
export interface GachaRange {
	/** Верхняя граница счётчика, при которой действует эта вероятность (включительно). */
	upToCounter: number;
	probability: number;
}
// Последний элемент gachaCurve — это "иначе": для counter больше upToCounter
// всех элементов берётся вероятность последнего элемента массива. Явного
// Infinity не храним — jsonb/JSON.stringify не умеет его сериализовать.

export type Tone = "general" | "targeted" | "sarcasm" | "praise";

export interface SummaryConfig {
	/** Раз в сколько залогированных сообщений темы обновлять роллинг-саммари. */
	everyNMessages: number;
	/** Сколько последних сырых сообщений скармливать модели при обновлении саммари. */
	lookbackMessages: number;
	/** Жёсткий предел длины самого саммари (символов) — чтобы оно само не разрослось и не стало новой статьёй расходов. */
	maxChars: number;
	/** completion-бюджет вызова, который генерирует саммари (отдельный от бюджета шутки — саммари должно быть короче). */
	maxTokens: number;
	/**
	 * false (по умолчанию) — каждое обновление саммари строится только из
	 * свежих lookbackMessages сообщений, старая сводка отбрасывается
	 * целиком ("снимок" последнего окна). true — старая сводка
	 * подмешивается в промпт обновления, и модель её ОБНОВЛЯЕТ, а не
	 * заменяет с нуля — так бот дольше "помнит" атмосферу чата, а не
	 * только последние ~40 сообщений. Компромисс: накопительный режим
	 * может со временем закреплять устойчивый образ конкретных
	 * участников ("Х вечно шутят про Y") — включать осознанно.
	 */
	cumulative: boolean;
}

export interface AiConfig {
	/** Какой провайдер сейчас активен — переключается в панели без передеплоя, оба ключа читаются из env (см. providers.ts). */
	provider: ProviderId;
	/** baseURL/модель/цена за токен на провайдера — редактируется в панели (например, при смене официальных цен). */
	providers: Record<ProviderId, ProviderModelConfig>;
	/** Глобальный (на весь бот, все чаты вместе) месячный $ потолок — 0 или меньше = не ограничен. См. budget.ts. */
	monthlyBudgetUsd: number;
	/** Шаблон системного промпта — {action} подставляется конкретным сценарием (см. actionsByTone), {target} внутри action — именем участника. */
	promptTemplate: string;
	/** Сценарии по категориям тона — можно использовать плейсхолдер {target}, при выборе targeted/praise он подставляется случайным активным участником. */
	actionsByTone: Record<Tone, string[]>;
	/** Относительные веса категорий при выборе тона (не обязаны суммироваться в 1 — нормализуются на лету). */
	toneWeights: Record<Tone, number>;
	/** Любое слово из списка в тексте — триггер (например ["Реван", "Реня"]). */
	triggerWords: string[];
	/** Общий кулдаун между ЛЮБЫМИ AI-ответами в чате (триггер-слово или гача) — персистентный, на чат. Не влияет на бесплатный флейвор "да"/"нет". */
	cooldownMinutes: number;
	/** Жёсткий потолок AI-вызовов в чате за 24 часа — страховка от неожиданного счёта при любом сбое остальных лимитов. */
	dailyCallCapPerChat: number;
	/**
	 * Короткое имя стикерпака (из ссылки t.me/addstickers/<имя>) — когда
	 * позвали по триггер-слову, а лимит (кулдаун/дневной кап/месячный
	 * бюджет) исчерпан, вместо тишины/AI-вызова отправляется случайный
	 * стикер оттуда — бесплатная замена, чат не остаётся совсем без ответа.
	 * Пусто — фолбэк выключен.
	 */
	stickerPackShortName: string;
	/** Отдельный (короткий) кулдаун именно на стикер-заглушку — иначе спам триггер-словом просто превращается в спам стикерами вместо AI-шуток. */
	stickerCooldownMinutes: number;
	/** completion-бюджет вызова с шуткой — шутка должна быть короткой репликой, не эссе. */
	maxTokens: number;
	/** Сколько символов "сырого" диалога брать в контекст последней шутки (плюс роллинг-саммари, если есть) — вместо фиксированного числа сообщений: держит стоимость входа предсказуемой независимо от активности чата. */
	contextCharBudget: number;
	/** Сколько последних сообщений темы просматривать, чтобы определить "кто сейчас активен" (для targeted/praise). */
	activeParticipantsLookback: number;
	summary: SummaryConfig;
	gachaCurve: GachaRange[];
	/** На каком значении счётчика гача срабатывает гарантированно. */
	gachaGuaranteedAt: number;
	yesAnswers: string[];
	noAnswers: string[];
	/** Шанс, что бот вообще ответит на "да"/"нет" (не отвечает на каждое) — не расходует AI-бюджет, чистый флейвор. */
	yesNoReplyProbability: number;
}

